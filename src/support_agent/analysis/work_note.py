"""Format a triage assessment as an internal ServiceNow work note.

Every note carries a machine-readable marker line. The marker prefix identifies
notes this agent wrote (duplicate prevention), and the run id identifies one
specific write (verification).
"""

from __future__ import annotations

from support_agent.analysis.models import TriageAssessment
from support_agent.retrieval.models import RetrievalResult, RetrievedDocument
from support_agent.servicenow.client import MAX_WORK_NOTE_CHARS

NOTE_TITLE = "AI Triage Assessment (Preliminary)"
TITLE_CHARS = 90
MARKER_PREFIX = "[support-agent:triage"
MARKER_VERSION = "v1"


def marker(run_id: str) -> str:
    return f"{MARKER_PREFIX} {MARKER_VERSION} run={run_id}]"


def is_triage_note(text: str) -> bool:
    return MARKER_PREFIX in text


def _bullets(items: list[str], numbered: bool = False) -> list[str]:
    if not items:
        return ["  - None identified"]
    return [f"  {i}. {item}" if numbered else f"  - {item}" for i, item in enumerate(items, 1)]


def _priority_basis(assessment: TriageAssessment) -> str:
    adjustment = assessment.customer_adjustment
    if adjustment is None or not adjustment.changed:
        basis = "from the impact/urgency matrix"
    else:
        basis = (
            f"matrix gives P{adjustment.base_priority}; raised for {adjustment.tier} "
            f"customer {adjustment.customer}"
        )
    return f"({basis}; not applied to this incident)"


def _short(text: str, limit: int = TITLE_CHARS) -> str:
    text = " ".join(text.split())
    return text if len(text) <= limit else text[: limit - 3].rstrip() + "..."


def _document_line(doc: RetrievedDocument, cited: set[str]) -> str:
    extra = []
    if doc.kind == "incident" and doc.state:
        extra.append(doc.state)
    if doc.reference:
        extra.append(f"upstream {doc.reference}, open")
    elif doc.url:
        extra.append(doc.url)
    extra.append(f"relevance {doc.relevance}/10")
    if doc.matched_by:
        extra.append(f"found by {' + '.join(doc.matched_by)}")
    if doc.id in cited:
        extra.append("used in analysis")
    return f"  - {doc.id} {_short(doc.title)} ({', '.join(extra)})"


def _related_knowledge(assessment: TriageAssessment, context: RetrievalResult | None) -> list[str]:
    heading = "Related knowledge (retrieved from the KB and incidents; verify before use):"
    if context is None:
        return [heading, "  - Not available: retrieval did not run or failed"]
    cited = set(assessment.analysis.relevant_documents)
    lines = [heading]
    groups = (
        ("KB articles", context.kb_articles),
        ("Known issues (open ERPNext defects)", context.known_issues),
        ("Similar incidents", context.similar_incidents),
    )
    for label, docs in groups:
        if docs:
            lines += [f"  {label}:", *(_document_line(doc, cited) for doc in docs)]
    if len(lines) == 1:
        lines.append(
            f"  - None above the relevance threshold ({context.threshold}/10). "
            "No KB answer or known issue found."
        )
    a = assessment.analysis
    if a.possible_match_id:
        lines.append(f"  Possible match: {a.possible_match_id} - {a.possible_match_reason}")
    return lines


def format_work_note(
    assessment: TriageAssessment, run_id: str, context: RetrievalResult | None = None
) -> str:
    a = assessment.analysis
    lines = [
        NOTE_TITLE,
        "",
        f"Summary: {a.summary}",
        "",
        f"Estimated impact: {a.impact} - {a.impact_reason}",
        f"Estimated urgency: {a.urgency} - {a.urgency_reason}",
        f"Recommended priority: {assessment.priority_label} {_priority_basis(assessment)}",
        f"Suggested category: {a.category}",
        "",
        *_related_knowledge(assessment, context),
        "",
        "Potential causes (hypotheses, not confirmed):",
        *_bullets(a.potential_causes),
        "",
        "Recommended initial troubleshooting:",
        *_bullets(a.troubleshooting_steps, numbered=True),
        "",
        "Missing information:",
        *_bullets(a.missing_information),
        "",
        "---",
        f"Generated by support-agent with {assessment.model}. Preliminary and unverified: "
        "confirm before acting. No incident fields were changed.",
        marker(run_id),
    ]
    note = "\n".join(lines)
    if len(note) > MAX_WORK_NOTE_CHARS:
        raise ValueError(f"Work note is {len(note)} characters (limit {MAX_WORK_NOTE_CHARS})")
    return note
