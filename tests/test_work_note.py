from __future__ import annotations

import pytest

from conftest import ANALYSIS, make_assessment, make_context
from support_agent.analysis.customer_tiers import PriorityAdjustment
from support_agent.analysis.work_note import (
    NOTE_TITLE,
    format_work_note,
    is_triage_note,
    marker,
)


def test_note_starts_with_title_and_contains_all_sections() -> None:
    note = format_work_note(make_assessment(), "abc123")
    assert note.startswith("AI Triage Assessment (Preliminary)\n")
    for expected in (
        "Summary: UI labels stay in English",
        "Estimated impact: Low - One user",
        "Estimated urgency: Low - No deadline",
        "Recommended priority: P5 - Planning (from the impact/urgency matrix; not applied",
        "Suggested category: Configuration",
        "Potential causes (hypotheses, not confirmed):",
        "  1. Reproduce with a test user set to Arabic",
        "Missing information:",
        "Generated by support-agent with claude-opus-5-5",
    ):
        assert expected in note


def test_marker_identifies_agent_notes_and_the_run() -> None:
    note = format_work_note(make_assessment(), "abc123")
    assert note.rstrip().endswith(marker("abc123"))
    assert is_triage_note(note)
    assert not is_triage_note(f"{NOTE_TITLE}\nwritten by a human")


def test_empty_lists_render_as_none_identified() -> None:
    analysis = ANALYSIS.model_copy(update={"missing_information": []})
    note = format_work_note(make_assessment(analysis=analysis), "r1")
    assert "Missing information:\n  - None identified" in note


def test_oversized_note_is_refused() -> None:
    analysis = ANALYSIS.model_copy(update={"potential_causes": ["x" * 500] * 10})
    with pytest.raises(ValueError, match="limit 4000"):
        format_work_note(make_assessment(analysis=analysis), "r1")


def test_note_explains_customer_priority_adjustment() -> None:
    adjustment = PriorityAdjustment(
        customer="Cobalt Ridge Manufacturing",
        tier="premium",
        base_priority=4,
        priority=3,
        rule="Raised from P4 to P3 (premium customer Cobalt Ridge Manufacturing)",
    )
    assessment = make_assessment(
        priority=3, priority_label="P3 - Moderate", customer_adjustment=adjustment
    )
    note = format_work_note(assessment, "abc123")
    assert (
        "Recommended priority: P3 - Moderate (matrix gives P4; raised for premium customer "
        "Cobalt Ridge Manufacturing; not applied to this incident)"
    ) in note


def test_note_lists_related_knowledge_and_marks_cited_documents() -> None:
    analysis = ANALYSIS.model_copy(
        update={
            "relevant_documents": ["KB0010005"],
            "possible_match_id": "KB0010074",
            "possible_match_reason": "Same duplicate credit-note symptom.",
        }
    )
    note = format_work_note(make_assessment(analysis=analysis), "abc123", make_context())
    for expected in (
        "Related knowledge (retrieved from the KB and incidents; verify before use):",
        "  KB articles:",
        "  - KB0010005 Title of KB0010005 (relevance 8/10, used in analysis)",
        "  Known issues (open ERPNext defects):",
        "  - KB0010074 Title of KB0010074 (upstream frappe/erpnext#1, open, relevance 8/10)",
        "  Similar incidents:",
        "  - INC0010006 Title of INC0010006 (New, relevance 8/10)",
        "  Possible match: KB0010074 - Same duplicate credit-note symptom.",
    ):
        assert expected in note
    assert note.index("Related knowledge") < note.index("Potential causes")


def test_note_says_when_nothing_was_found() -> None:
    empty = make_context(kb_articles=[], known_issues=[], similar_incidents=[])
    note = format_work_note(make_assessment(), "abc123", empty)
    assert "  - None above the relevance threshold (7/10)." in note


def test_note_says_when_retrieval_did_not_run() -> None:
    note = format_work_note(make_assessment(), "abc123")
    assert "  - Not available: retrieval did not run or failed" in note
